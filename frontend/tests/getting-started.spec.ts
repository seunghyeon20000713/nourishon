import { test, expect } from '@playwright/test'

test('첫 이용 안내가 프로필 계산과 첫 식사 기록을 반영한다', async ({ page }) => {
  await page.goto('/#dashboard')
  const guide = page.locator('.getting-started')
  await expect(guide.locator('summary')).toContainText('0 / 3 단계')
  await expect(guide.locator('[aria-current=step]')).toContainText('내 몸과 목표 입력')
  await guide.getByRole('button', { name: '프로필 입력하기' }).click()
  await page.getByLabel('나이 (세)', { exact: true }).fill('30')
  await page.getByLabel('키 (cm)', { exact: true }).fill('170')
  await page.getByLabel('체중 (kg)', { exact: true }).fill('70')
  await page.getByLabel('임신·수유 중이').check()
  await page.getByRole('button', { name: '프로필 적용 및 참고 목표 계산' }).click()
  await expect(page.getByText('2167 kcal/일')).toBeVisible()
  await page.getByRole('button', { name: '영양 대시보드', exact: true }).click()
  await expect(guide.locator('summary')).toContainText('2 / 3 단계')
  await expect(guide.locator('[aria-current=step]')).toContainText('첫 식사 기록')
  await guide.getByRole('button', { name: '목표와 근거 보기' }).click()
  await expect(page.getByRole('heading', { name: '참고 목표', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '영양 대시보드', exact: true }).click()
  await guide.getByRole('button', { name: '식사 기록하기', exact: true }).click()
  await page.getByRole('textbox', { name: '음식 이름' }).fill('국밥_돼지머리')
  await page.getByRole('button', { name: '검색', exact: true }).click()
  await page.getByRole('button', { name: /국밥_돼지머리 추가/ }).first().click()
  await page.getByRole('button', { name: '영양 합계 계산' }).click()
  await page.getByRole('button', { name: '식사 기록에 추가', exact: true }).click()
  await page.getByRole('button', { name: '영양 대시보드', exact: true }).click()
  await expect(guide.locator('summary')).toContainText('첫 이용 준비 완료')
  await expect(guide).not.toHaveAttribute('open')
  await guide.locator('summary').click()
  await expect(guide.locator('summary')).toContainText('3 / 3 단계')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
