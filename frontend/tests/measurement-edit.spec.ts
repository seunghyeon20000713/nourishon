import { test, expect } from '@playwright/test'

test('측정 수정·취소·검증 오류·삭제와 목표 유지', async ({ page }) => {
  await page.goto('/#dashboard')
  await page.getByRole('button', { name: '내 몸과 목표', exact: true }).click()
  await page.getByLabel('나이 (세)', { exact: true }).fill('30')
  await page.getByLabel('키 (cm)', { exact: true }).fill('170')
  await page.getByLabel('체중 (kg)', { exact: true }).fill('70')
  await page.getByLabel('임신·수유 중이').check()
  await page.getByRole('button', { name: '프로필 적용 및 참고 목표 계산' }).click()
  await expect(page.getByText('2167 kcal/일')).toBeVisible()
  const section = page.locator('.measurement-section')
  await section.getByRole('button', { name: '측정 수정', exact: true }).click()
  const form = page.getByRole('form', { name: '측정 기록 수정' })
  await form.getByLabel('이력 체중 (kg)', { exact: true }).fill('69')
  await form.getByRole('button', { name: '측정 수정 취소' }).click()
  await expect(section.getByRole('cell', { name: '70', exact: true })).toBeVisible()
  await section.getByRole('button', { name: '측정 수정', exact: true }).click()
  await form.getByLabel('이력 골격근량 (kg)', { exact: true }).fill('60')
  await form.getByLabel('이력 체지방량 (kg)', { exact: true }).fill('20')
  await form.getByRole('button', { name: '측정 변경 적용' }).click()
  await expect(form.getByRole('alert')).toBeVisible()
  await expect(section.getByRole('cell', { name: '70', exact: true })).toBeVisible()
  await form.getByLabel('이력 골격근량 (kg)', { exact: true }).fill('')
  await form.getByLabel('이력 체지방량 (kg)', { exact: true }).fill('0')
  await form.getByLabel('이력 체중 (kg)', { exact: true }).fill('69')
  await form.getByRole('button', { name: '측정 변경 적용' }).click()
  await expect(form).toBeHidden()
  await expect(section.getByRole('cell', { name: '69', exact: true })).toBeVisible()
  await expect(section.getByRole('cell', { name: '0', exact: true })).toBeVisible()
  await expect(page.getByLabel('체중 (kg)', { exact: true })).toHaveValue('70')
  await expect(page.getByText('2167 kcal/일')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  page.once('dialog', dialog => dialog.dismiss())
  await section.getByRole('button', { name: '측정 삭제', exact: true }).click()
  await expect(section.getByRole('cell', { name: '69', exact: true })).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await section.getByRole('button', { name: '측정 삭제', exact: true }).click()
  await expect(section.getByRole('table')).toHaveCount(0)
  await expect(page.getByText('2167 kcal/일')).toBeVisible()
})
