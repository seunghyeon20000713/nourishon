import { test, expect } from '@playwright/test'

test('기록 수정의 취소·재계산·0g·오류 시 원본 유지', async ({ page }) => {
  await page.goto('/#dashboard')
  await page.getByRole('button', { name: '식사 분석', exact: true }).click()
  await page.getByRole('textbox', { name: '음식 이름' }).fill('국밥_돼지머리')
  await page.getByRole('button', { name: '검색', exact: true }).click()
  await page.getByRole('button', { name: /국밥_돼지머리 추가/ }).first().click()
  await page.getByRole('button', { name: '영양 합계 계산' }).click()
  await page.getByRole('button', { name: '식사 기록에 추가', exact: true }).click()
  await page.getByRole('button', { name: '기록과 분석', exact: true }).click()
  const record = page.locator('.record').first()
  const original = await record.locator('p').first().textContent()
  await record.getByRole('button', { name: '기록 수정', exact: true }).click()
  const form = page.getByRole('form', { name: '식사 기록 수정' })
  const grams = form.getByRole('spinbutton')
  await grams.fill('200')
  await form.getByRole('button', { name: '수정 취소' }).click()
  await expect(record.locator('p').first()).toHaveText(original!)
  await record.getByRole('button', { name: '기록 수정', exact: true }).click()
  await grams.fill('-1')
  await form.getByRole('button', { name: '변경 적용' }).click()
  await expect(form).toBeVisible()
  await grams.fill('200')
  await form.getByLabel('식사 구분', { exact: true }).selectOption('점심')
  const calculated = page.waitForResponse(response => response.url().endsWith('/api/meals/calculate') && response.request().method() === 'POST')
  await form.getByRole('button', { name: '변경 적용' }).click()
  const result = await (await calculated).json()
  expect(result.foods[0].intake_g).toBe(200)
  await expect(record.locator('p').first()).toContainText('200g')
  await expect(record.getByRole('heading')).toContainText('점심')
  await record.getByRole('button', { name: '기록 수정', exact: true }).click()
  await grams.fill('300')
  await page.route('**/api/meals/calculate', route => route.fulfill({ status: 503, json: {} }))
  await form.getByRole('button', { name: '변경 적용' }).click()
  await expect(form.getByRole('alert')).toBeVisible()
  await expect(record.locator('p').first()).toContainText('200g')
  await page.unroute('**/api/meals/calculate')
  await grams.fill('0')
  await form.getByRole('button', { name: '변경 적용' }).click()
  await expect(form).toBeHidden()
  await expect(record.locator('p').first()).toContainText('0g')
  await expect(page.locator('.wellness-panel .nutrient-card').first()).toContainText('0 kcal')
  await page.setViewportSize({ width: 390, height: 844 })
  await record.getByRole('button', { name: '기록 수정', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const before = await page.locator('.wellness-panel .nutrient-card').allTextContents()
  const date = form.locator('input[type=date]')
  const previous = new Date(`${await date.inputValue()}T12:00:00Z`)
  previous.setUTCDate(previous.getUTCDate() - 1)
  const selected = previous.toISOString().slice(0, 10)
  let recalculations = 0
  await page.route('**/api/meals/calculate', route => { recalculations++; return route.abort() })
  await date.fill(selected)
  await form.getByRole('button', { name: '변경 적용' }).click()
  await expect(form).toBeHidden()
  await expect(record.getByRole('heading')).toContainText(selected)
  expect(await page.locator('.wellness-panel .nutrient-card').allTextContents()).toEqual(before)
  expect(recalculations).toBe(0)
})
