import { test, expect } from '@playwright/test'

test('개인 홈·계정 진입·내 정보·모바일 바로가기', async ({ page }) => {
  await page.goto('/#dashboard')
  await expect(page.getByRole('heading', { name: '오늘의 나를 기록해요' })).toBeVisible()
  const account = page.locator('#account-tools')
  await expect(account.locator(':scope > summary')).toContainText('로그인 / 회원가입')
  await account.locator(':scope > summary').click()
  await expect(page.getByRole('button', { name: '로그인 선택', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '회원가입 선택', exact: true }).click()
  await expect(page.getByLabel('아이디', { exact: true })).toHaveAttribute('minlength', '4')
  await page.getByRole('button', { name: '로그인 선택', exact: true }).click()
  await page.keyboard.press('Escape')
  const profile = page.locator('details.profile-tools')
  await profile.locator(':scope > summary').click()
  await expect(profile.getByLabel('새 프로필 별칭')).toBeHidden()
  await profile.getByRole('button', { name: '내 정보 수정' }).click()
  await expect(page.getByRole('heading', { name: '내 몸과 목표', exact: true })).toBeVisible()
  await expect(profile).not.toHaveAttribute('open')
  await page.getByRole('button', { name: '영양 대시보드', exact: true }).click()
  await expect(page.getByRole('complementary', { name: '하루 기록 바로가기' })).toBeVisible()
  await page.getByRole('button', { name: '운동 기록하기', exact: true }).click()
  await expect(page.locator('#activity-log-title')).toBeInViewport()
  await page.setViewportSize({ width: 390, height: 844 })
  const bottom = page.getByRole('navigation', { name: '빠른 메뉴' })
  await expect(bottom).toBeVisible()
  await bottom.getByRole('button', { name: '영양 대시보드', exact: true }).click()
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: '/tmp/nourishon-personal-after-mobile.png', fullPage: true })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await bottom.getByRole('button', { name: '기록과 분석', exact: true }).click()
  await expect(page.getByRole('heading', { name: '식사 기록과 기간 분석' })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: '영양 대시보드', exact: true }).click()
  await page.screenshot({ path: '/tmp/nourishon-personal-after-home.png' })
  await account.locator(':scope > summary').click()
  await page.screenshot({ path: '/tmp/nourishon-personal-after-account.png' })
})
