import { test, expect } from '@playwright/test'

test('주·월 경계와 결측·0·부분 기록 평균 및 체성분 변화', async ({ page }) => {
  await page.goto('/#dashboard')
  await page.evaluate(() => {
    const meal = (date: string, value: number | null, partial = false) => ({ id: crypto.randomUUID(), date, kind: '점심', calculation: { foods: [], totals: { energy: { unit: 'kcal', known_total: value, missing_count: value === null || partial ? 1 : 0, status: value === null ? 'missing' : partial ? 'partial' : 'complete' } } } })
    localStorage.setItem('nourishon-local-mvp-v1', JSON.stringify({ profile: null, estimate: null,
      records: [meal('2024-02-26', 100, true), meal('2024-02-27', 0), meal('2024-02-28', null), meal('2024-02-01', 200), meal('2024-03-01', 400)],
      measurements: [{ id: 'first', measured_on: '2024-02-01', weight_kg: 70, body_fat_percent: 20, fat_mass_kg: 14 }, { id: 'last', measured_on: '2024-02-29', weight_kg: 69, body_fat_percent: 18, skeletal_muscle_kg: 30 }, { id: 'outside', measured_on: '2024-03-01', weight_kg: 68 }],
    }))
  })
  await page.reload()
  await page.getByRole('button', { name: '기록과 분석', exact: true }).click()
  await page.getByLabel('조회 날짜', { exact: true }).fill('2024-02-29')
  const section = page.locator('.period-analysis')
  await expect(section).toContainText('2024-02-26 ~ 2024-03-03')
  await expect(section.locator('.period-summary')).toContainText('166.67 kcal')
  await expect(section.getByRole('button', { name: '2024-02-27 상세 기록 보기' })).toContainText('0 kcal')
  await expect(section.getByRole('button', { name: '2024-02-28 상세 기록 보기' })).toContainText('열량 정보 없음')
  await expect(section.getByRole('button', { name: '2024-02-29 상세 기록 보기' })).toContainText('미기록')
  await section.getByRole('button', { name: '월간', exact: true }).click()
  await expect(section).toContainText('2024-02-01 ~ 2024-02-29')
  await expect(section.locator('.period-summary')).toContainText('4건 · 4일')
  await expect(section.locator('.period-summary')).toContainText('300 kcal')
  await expect(section.locator('.period-summary')).toContainText('100 kcal')
  await expect(section.locator('.period-summary')).toContainText('분모 3일')
  const nutrients = section.getByRole('table').first()
  await expect(nutrients.getByRole('row', { name: /열량/ })).toContainText('일부 정보 누락')
  await expect(nutrients.getByRole('row', { name: /식이섬유/ })).toContainText('영양 정보 없음')
  const body = section.getByRole('table').last()
  await expect(body.getByRole('row', { name: /^체중 / })).toContainText('-1 kg')
  await expect(body.getByRole('row', { name: /^체지방률 / })).toContainText('-2 %p')
  await expect(body.getByRole('row', { name: /^골격근량 / })).toContainText('다른 날짜의 측정 2회 필요')
  await page.screenshot({path:'/tmp/nourishon-period-desktop.png',fullPage:true})
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({path:'/tmp/nourishon-period-mobile.png',fullPage:true})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await section.getByRole('button', { name: '2024-02-01 상세 기록 보기' }).click()
  await expect(page.getByRole('heading', { name: '2024-02-01 · 점심', exact: true })).toBeVisible()
  await page.getByLabel('조회 날짜', { exact: true }).fill('2024-01-01')
  await expect(section).toContainText('2024-01-01 ~ 2024-01-31')
  await expect(section.locator('.period-summary')).toContainText('0건 · 0일')
  await expect(section.locator('.period-summary')).toContainText('분모 0일')
  await section.getByRole('button', { name: '주간', exact: true }).click()
  await page.getByLabel('조회 날짜', { exact: true }).fill('2023-12-31')
  await expect(section).toContainText('2023-12-25 ~ 2023-12-31')
})
