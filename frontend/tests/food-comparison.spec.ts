import { test, expect } from '@playwright/test'

test('실제 음식 비교 → 성분 순서·페이지 → 식사 계산과 기록', async ({ page }) => {
  await page.goto('/#dashboard')
  await page.getByRole('button',{name:'생활 개선',exact:true}).click()
  const guide=page.locator('.weekly-guidance')
  await guide.locator('[data-guidance=food_records]').getByRole('button',{name:'관련 음식 비교'}).click()
  const section=page.locator('.food-comparison')
  await expect(section.getByLabel('비교 성분',{exact:true})).toHaveValue('fiber')
  await section.getByLabel('비교할 음식 이름',{exact:true}).fill('두부')
  const found=page.waitForResponse(response=>response.url().includes('/api/foods/compare?')&&response.ok())
  await section.getByRole('button',{name:'음식 비교 검색',exact:true}).click()
  const initial=await (await found).json()
  expect(initial.focus).toBe('fiber')
  await expect(section.getByRole('table')).toBeVisible()
  await expect(section.getByRole('caption')).toContainText('100g당')
  if(initial.total>8){await section.getByRole('button',{name:'비교 다음 결과'}).click();await expect(section.locator('.comparison-pages')).toContainText('9~')}
  await section.getByLabel('비교 성분',{exact:true}).selectOption('sodium')
  const sorted=page.waitForResponse(response=>response.url().includes('focus=sodium')&&response.ok())
  await section.getByRole('button',{name:'음식 비교 검색',exact:true}).click()
  const results=await (await sorted).json()
  const values=results.items.map((food:{nutrients:{sodium:{per_100g:number|null}}})=>food.nutrients.sodium.per_100g).filter((value:number|null)=>value!==null)
  expect(values).toEqual([...values].sort((a:number,b:number)=>a-b))
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'/tmp/nourishon-food-comparison-mobile.png',fullPage:true})
  await section.getByRole('button',{name:/식사 계산에 담기$/}).first().click()
  await expect(page.getByRole('heading',{name:'식사 기록과 영양 계산'})).toBeVisible()
  await page.getByRole('spinbutton',{name:/섭취량$/}).fill('150')
  const calculation=page.waitForResponse(response=>response.url().endsWith('/api/meals/calculate')&&response.ok())
  await page.getByRole('button',{name:'영양 합계 계산'}).click()
  const meal=await (await calculation).json()
  expect(meal.foods[0].food_code).toBe(results.items[0].food_code)
  expect(meal.foods[0].intake_g).toBe(150)
  await page.getByRole('button',{name:'식사 기록에 추가',exact:true}).click()
  await page.getByRole('button',{name:'기록과 분석',exact:true}).click()
  await expect(page.locator('.record').first()).toContainText('150g')
})

test('음식 비교 검색 결과 없음과 연결 오류', async ({page})=>{
 await page.goto('/#dashboard')
 await page.getByRole('button',{name:'생활 개선',exact:true}).click()
 const section=page.locator('.food-comparison')
 await section.getByLabel('비교할 음식 이름',{exact:true}).fill('일치하지않는연습검색어987654')
 await section.getByRole('button',{name:'음식 비교 검색',exact:true}).click()
 await expect(section.getByText('일치하는 식품이 없습니다. 다른 이름으로 검색해주세요.')).toBeVisible()
 await page.route('**/api/foods/compare?**',route=>route.fulfill({status:503,json:{}}))
 await section.getByRole('button',{name:'음식 비교 검색',exact:true}).click()
 await expect(section.getByRole('alert')).toContainText('서버 연결')
})
