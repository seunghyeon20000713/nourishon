import { test, expect } from '@playwright/test'

test('양쪽 햄버거 버튼으로 메뉴 이름 펼침과 화면 이동', async ({ page }) => {
  await page.goto('/#dashboard')
  const left = page.getByRole('button', { name: '왼쪽 메뉴 펼치기', exact: true })
  const top = page.getByRole('button', { name: '상단 메뉴 펼치기', exact: true })
  await expect(left).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('heading', { name: '기록으로 보는 나의 영양' })).toBeVisible()
  await left.click()
  await expect(top).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('navigation', { name: '주 메뉴' }).getByText('내 몸과 목표')).toBeVisible()
  await page.screenshot({ path: '/tmp/nourishon-menu-desktop.png' })
  await top.click()
  await expect(left).toHaveAttribute('aria-expanded', 'false')
  await top.click()
  await page.keyboard.press('Escape')
  await expect(left).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await top.click()
  await page.screenshot({ path: '/tmp/nourishon-menu-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '내 몸과 목표', exact: true }).click()
  await expect(page.getByRole('heading', { name: '내 몸과 목표', exact: true })).toBeVisible()
  await expect(left).toHaveAttribute('aria-expanded', 'false')
})
